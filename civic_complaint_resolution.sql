USE civic_complaint_intelligence;
SHOW TABLES;

# Number of records in tables
SELECT COUNT(*) FROM agencies;
SELECT COUNT(*) FROM complaint_categories;
SELECT COUNT(*) FROM complaints;

# records in compalaint table
SELECT * FROM vw_complaint_details LIMIT 10;

# total records in complaint 
SELECT COUNT(*) AS TOTAL_COMPLAINTS, COUNT(DISTINCT COMPLAINT_ID)AS UNIQUE_COMPLAINTS
FROM COMPLAINTS;

# how long each complaint took to resolve
SELECT COMPLAINT_ID, COMPLAINT_TYPE, CREATED_DATE, CLOSED_DATE, 
	   ROUND( TIMESTAMPDIFF(MINUTE, CREATED_DATE, CLOSED_DATE) / 60.0, 2) AS RESOLUTION_HOURS
FROM VW_COMPLAINT_DETAILS 
WHERE CLOSED_DATE IS NOT NULL
AND CLOSED_DATE >=CREATED_DATE
ORDER BY RESOLUTION_HOURS DESC
LIMIT 10;

# Which complaint types occur most frequently
SELECT COMPLAINT_TYPE, COUNT(*) AS TOTAL_COMPLAINTS 
FROM VW_COMPLAINT_DETAILS
GROUP BY COMPLAINT_TYPE
ORDER BY TOTAL_COMPLAINTS DESC
LIMIT 10;

# Agency Workload Analysis - agencies handling the highest number of complaints
SELECT AGENCY_CODE, AGENCY_NAME, COUNT(*) AS TOTAL_COMPLAINTS 
FROM VW_COMPLAINT_DETAILS
GROUP BY AGENCY_CODE, AGENCY_NAME 
ORDER BY TOTAL_COMPLAINTS DESC
LIMIT 10;

# Which borough has the most complaints
SELECT BOROUGH, COUNT(*) AS TOTAL_COMPLAINTS, 
       ROUND( COUNT(*) * 100.0 / ( SELECT COUNT(*) FROM COMPLAINTS), 2) AS PERCENTAGE_OF_COMPLAINTS
FROM COMPLAINTS
GROUP BY BOROUGH
ORDER BY TOTAL_COMPLAINTS DESC;

# How long does it take to resolve complaints
SELECT COUNT(*) AS CLOSED_COMPLAINTS,
       ROUND(AVG(RESOLUTION_HOURS),2) AS AVERAGE_RESOLUTION_HOURS,
       ROUND(MIN(RESOLUTION_HOURS),2) AS MINIMUM_RESOLUTION_HOURS,
       ROUND(MAX(RESOLUTION_HOURS),2) AS MAXIMUM_RESOLUTION_HOURS
FROM VW_COMPLAINT_DETAILS
WHERE RESOLUTION_HOURS IS NOT NULL;

# Which complaint types take the longest to resolve
SELECT COMPLAINT_TYPE, 
	   COUNT(*) AS CLOSED_COMPLAINTS,
       ROUND(AVG(RESOLUTION_HOURS),2) AS AVERAGE_RESOLUTION_HOURS 
FROM VW_COMPLAINT_DETAILS
WHERE RESOLUTION_HOURS IS NOT NULL
GROUP BY COMPLAINT_TYPE
HAVING COUNT(*) >= 3
ORDER BY AVERAGE_RESOLUTION_HOURS DESC
LIMIT 10;

# Top 3 Complaint Types in Each Borough
WITH BOROUGH_COMPLAINTS AS (
	SELECT 
		BOROUGH,
        COMPLAINT_TYPE,
        COUNT(*) AS TOTAL_COMPLAINTS
	FROM VW_COMPLAINT_DETAILS
    WHERE LOWER(TRIM(BOROUGH)) <> 'UNKNOWN'
    GROUP BY BOROUGH, COMPLAINT_TYPE
),
RANKED_COMPLAINTS AS (
	SELECT
		BOROUGH,
        COMPLAINT_TYPE,
        TOTAL_COMPLAINTS,
        DENSE_RANK() OVER(
			PARTITION BY BOROUGH
            ORDER BY TOTAL_COMPLAINTS DESC
		) AS COMPLAINT_RANK
	FROM BOROUGH_COMPLAINTS
) 
SELECT
	BOROUGH,
    COMPLAINT_TYPE,
    TOTAL_COMPLAINTS,
    COMPLAINT_RANK
FROM RANKED_COMPLAINTS
WHERE COMPLAINT_RANK <= 3
ORDER BY BOROUGH, COMPLAINT_RANK;

# Complaint Resolution Time Categories
WITH RESOLUTION_TIMES AS(
	SELECT
		 COMPLAINT_ID,
         RESOLUTION_HOURS
	FROM VW_COMPLAINT_DETAILS
    WHERE RESOLUTION_HOURS IS NOT NULL
)
SELECT 
	CASE
		WHEN RESOLUTION_HOURS < 1 THEN 'UNDER 1 HOUR'
        WHEN RESOLUTION_HOURS < 6 THEN '1 TO UNDER 6 HOURS'
        WHEN RESOLUTION_HOURS < 24 THEN '6 TO UNDER 24 HOURS'
        ELSE '24 HOURS OR MORE'
	END AS RESOLUTION_CATEGORY,
ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM RESOLUTION_TIMES), 2) AS PERCENTAGE
FROM RESOLUTION_TIMES
GROUP BY RESOLUTION_CATEGORY 
ORDER BY 
	CASE RESOLUTION_CATEGORY
		WHEN 'UNDER 1 HOUR' THEN 1
        WHEN '1 TO UNDER 6 HOURS' THEN 2
        WHEN '6 TO UNDER 24 HOURS' THEN 3
	    ELSE 4
	END;